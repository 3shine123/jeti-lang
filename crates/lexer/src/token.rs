use std::fmt;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TokenKind {
    // Identifiers / Keywords
    Identifier,
    Keyword,

    // Literals
    Integer,
    Float,
    String,
    AtString,
    AtNumber,
    /// `@(expr)` — boxed-expression literal. The checker rewrites it to the
    /// `NPNumber` factory matching the expression's static type.
    AtLParen,
    /// `@'c'` — boxed character literal (`NPNumber`).
    AtChar,
    /// `@YES` / `@NO` / `@true` / `@false` — boxed BOOL literal.
    AtBool,
    Char,
    Bool,

    // Operators
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Ampersand,
    Pipe,
    Caret,
    Tilde,
    Exclam,
    Less,
    Greater,
    Assign,
    Comma,
    Dot,
    Semicolon,
    Colon,
    ColonColon,
    LBracket,
    RBracket,
    AtArray,
    LBrace,
    RBrace,
    AtDict,
    LParen,
    RParen,
    Arrow,
    Ellipsis,

    // Compound operators
    PlusAssign,
    MinusAssign,
    StarAssign,
    SlashAssign,
    PercentAssign,
    AndAssign,
    OrAssign,
    XorAssign,
    LShiftAssign,
    RShiftAssign,
    Eq,
    Neq,
    Leq,
    Geq,
    LShift,
    RShift,
    LogicalAnd,
    LogicalOr,
    Incr,
    Decr,
    ArrowStar,
    Question,

    // Preprocessor
    PpHash,
    PpDoubleHash,

    // Special
    Newline,
    Eof,
    Error,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeywordKind {
    AtInterface,
    AtImplementation,
    AtEnd,
    AtProperty,
    AtSynthesize,
    AtDynamic,
    AtSelector,
    AtEncode,
    AtProtocol,
    AtOptional,
    AtRequired,
    AtClass,
    AtTry,
    /// `@defer` — scope-exit execution block (Go-style defer). `@` because C
    /// has no syntax slot for "run this at every exit of my enclosing block";
    /// without it the programmer hand-writes cleanup at every return/break/
    /// throw. See AGENTS.md `@defer` section.
    AtDefer,
    AtCatch,
    AtFinally,
    AtThrow,
    /// `@throws` — trailing declaration annotation ("this method may throw"),
    /// distinct from the `@throw` statement. See AGENTS.md `@throws` section.
    AtThrows,
    AtSynchronized,
    AtAutoreleasepool,
    AtPublic,
    AtPackage,
    AtProtected,
    AtPrivate,
    AtDefs,
    AtNamespace,
    AtEndNamespace,
    AtUsing,
    AtNoArc,
    AtReadwrite,
    AtReadonly,
    AtWeak,
    AtStrong,
    AtAssign,
    AtRetain,
    AtCopy,
    AtNonatomic,
    AtGetter,
    AtSetter,

    Yes,
    No,
    Nil,
    Null,

    Self_,
    Super,
    Cmd,

    Block,
    Weak,
    Strong,
    Autoreleasing,
    UnsafeUnretained,

    Instancetype,
    Id,
    Class,
    Sel,
    Bool,
    Imp,
    NpZone,

    Return,
    If,
    Else,
    Switch,
    Case,
    Default,
    While,
    Do,
    For,
    In,
    Break,
    Continue,
    Goto,
    Sizeof,
    Typeof,
    Struct,
    Union,
    Enum,
    Typedef,

    Void,
    Char,
    Short,
    Int,
    Long,
    Float,
    Double,
    /// C99 `_Complex` — always follows `float`/`double` in a type specifier.
    Complex,
    Signed,
    Unsigned,
    Const,
    Volatile,
    Static,
    Extern,
    Auto,
    Register,
    Inline,
    Restrict,

    Import,
    Include,
    Define,
    Ifdef,
    Ifndef,
    Endif,
    Pragma,
    Elif,
    Undef,

    Asm,

    Extension,
    Alignof,

    None,
}

#[derive(Debug, Clone)]
pub struct Token {
    pub kind: TokenKind,
    pub keyword: KeywordKind,
    pub start: usize,
    pub length: usize,
    pub line: usize,
    pub column: usize,
    pub char_val: u8,
}

impl Token {
    pub fn text<'a>(&self, source: &'a str) -> &'a str {
        &source[self.start..self.start + self.length]
    }
}

